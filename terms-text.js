window.showTermsText = function(key){
  const t = window.OM_TERMS[key];
  if(!t) return;
  let box = document.getElementById('omTermsView');
  if(!box){
    box = document.createElement('div');
    box.id = 'omTermsView';
    box.className = 'fixed inset-0 bg-slate-900/50 flex items-center justify-center px-4 py-8 z-[300]';
    box.onclick = e => { if(e.target===box) box.remove(); };
    document.body.appendChild(box);
  }
  const esc = v => String(v??'').replace(/[&<>"']/g,
    c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  box.innerHTML = `
    <div class="bg-white rounded-2xl max-w-lg w-full max-h-[85vh] flex flex-col">
      <div class="flex items-center justify-between gap-3 px-6 py-4 border-b border-slate-100 shrink-0">
        <h3 class="font-bold text-slate-900 text-[15px] min-w-0">${esc(t.title)}</h3>
        <button onclick="document.getElementById('omTermsView').remove()"
          class="text-slate-400 hover:text-slate-600 text-xl leading-none shrink-0" aria-label="닫기">&times;</button>
      </div>
      <div class="px-6 py-5 overflow-y-auto overscroll-contain text-[13px] text-slate-600 leading-relaxed whitespace-pre-line">${esc(t.body)}</div>
      <div class="flex gap-2 px-6 py-4 border-t border-slate-100 shrink-0">
        ${t.link ? `<a href="${t.link}" target="_blank"
          class="flex-1 py-2.5 rounded-lg border border-indigo-200 text-indigo-600 text-[13px] font-bold hover:bg-indigo-50 transition text-center">${esc(t.linkLabel||'전문 보기')} ↗</a>` : ''}
        <button onclick="document.getElementById('omTermsView').remove()"
          class="flex-1 py-2.5 rounded-lg border border-slate-200 text-slate-600 text-[13px] font-bold hover:bg-slate-50 transition">닫기</button>
      </div>
    </div>`;
};
